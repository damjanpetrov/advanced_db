-- [v2] Опционална врска до нарачка, resolved_at, жалбата е задолжителна.
CREATE TABLE customer_support_report
(
    report_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint    TEXT      NOT NULL CHECK (complaint <> ''),
    date         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    issue_solved BOOLEAN   NOT NULL DEFAULT FALSE,
    resolved_at  TIMESTAMP,
    employee_id  INT,
