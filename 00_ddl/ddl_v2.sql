DROP TABLE IF EXISTS wishlist_items, wishlist, customer_support_report, returns,
    review, serial_number, order_item, installments, orders, shipping, promotion,
    price_history, warehouse, product_supplier, product_attribute, product,
    category, supplier, customer_attribute, address_customer, address, customer,
    employee_role, employee, role_permission, permission, role CASCADE;

-- =========================
-- ROLE & PERMISSIONS
-- =========================

CREATE TABLE role
(
    role_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role    VARCHAR(50) NOT NULL UNIQUE CHECK (role <> '')
);

-- [v2] permissions -> permission; додадено име (код) на дозволата.
--      Во ЕР: тргнете role_id и is_allowed_to_access од оваа табела —
--      врската со улогата веќе ја прави role_permission.
CREATE TABLE permission
(
    permission_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,          -- пр. 'order.refund'
    description   TEXT
);

CREATE TABLE role_permission
(
    role_permission_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id            INT NOT NULL,
    permission_id      INT NOT NULL,
    CONSTRAINT fk_role_permission_role
        FOREIGN KEY (role_id) REFERENCES role (role_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_role_permission_permission
        FOREIGN KEY (permission_id) REFERENCES permission (permission_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_role_permission UNIQUE (role_id, permission_id)
);

-- =========================
-- EMPLOYEE
-- =========================

-- [v2] Тргнато returnsreturn_id од ЕР (returns веќе има employee_id).
-- [v2] Поправен regex за телефон: +389 + 8 цифри ИЛИ 0 + 8 цифри
--      (стариот одбиваше валиден број како +38970123456).
-- [v2] Email е уникатен без разлика на големи/мали букви (индекс подолу).
CREATE TABLE employee
(
    employee_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL CHECK (name <> ''),
    surname     VARCHAR(100) NOT NULL CHECK (surname <> ''),
    email       VARCHAR(100) NOT NULL
        CHECK (email ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
    password    VARCHAR(255) NOT NULL CHECK (length(password) >= 8), -- хеш, не чиста лозинка
    phone       VARCHAR(20)
        CHECK (phone IS NULL OR phone ~ '^(\+389[0-9]{8}|0[0-9]{8})$'),
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active   BOOLEAN       NOT NULL DEFAULT TRUE,
    salary      NUMERIC(10, 2) CHECK (salary IS NULL OR salary >= 0)
);
CREATE UNIQUE INDEX uq_employee_email ON employee (lower(email));

CREATE TABLE employee_role
(
    employee_role_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id      INT NOT NULL,
    role_id          INT NOT NULL,
    CONSTRAINT fk_employee_role_employee
        FOREIGN KEY (employee_id) REFERENCES employee (employee_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_employee_role_role
        FOREIGN KEY (role_id) REFERENCES role (role_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_employee_role UNIQUE (employee_id, role_id)
);

-- =========================
-- CUSTOMER
-- =========================

CREATE TABLE customer
(
    customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL CHECK (name <> ''),
    surname     VARCHAR(100) NOT NULL CHECK (surname <> ''),
    email       VARCHAR(100) NOT NULL
        CHECK (email ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
    password    VARCHAR(255) NOT NULL CHECK (length(password) >= 8),
    phone       VARCHAR(20)
        CHECK (phone IS NULL OR phone ~ '^(\+389[0-9]{8}|0[0-9]{8})$'),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active   BOOLEAN   NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uq_customer_email ON customer (lower(email));

-- [v2] Табелата постоеше во ЕР и во описот, а недостигаше во DDL.
CREATE TABLE customer_attribute
(
    attribute_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    text         VARCHAR(255),
    customer_id  INT NOT NULL,
    CONSTRAINT fk_customer_attribute_customer
        FOREIGN KEY (customer_id) REFERENCES customer (customer_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_customer_attribute UNIQUE (customer_id, name)
);

CREATE TABLE address
(
    address_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    street     VARCHAR(100) NOT NULL,
    number     VARCHAR(20),
    city       VARCHAR(100) NOT NULL,
    country    VARCHAR(100) NOT NULL DEFAULT 'North Macedonia'
);

-- [v2] UNIQUE (customer_id, address_id): иста адреса не се врзува двапати,
--      и овозможува композитен FK од orders (адресата мора да е на купувачот).
CREATE TABLE address_customer
(
    address_customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         INT NOT NULL,
    address_id          INT NOT NULL,
    CONSTRAINT fk_address_customer_customer
        FOREIGN KEY (customer_id) REFERENCES customer (customer_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_address_customer_address
        FOREIGN KEY (address_id) REFERENCES address (address_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_address_customer UNIQUE (customer_id, address_id)
);

-- =========================
-- SUPPLIER
-- =========================

-- [v2] email UNIQUE (во ЕР и во описот беше уникатен, во DDL не).
--      Телефонот на добавувач може да е странски -> поопшт формат.
CREATE TABLE supplier
(
    supplier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL CHECK (name <> ''),
    company     VARCHAR(100),
    email       VARCHAR(100)
        CHECK (email IS NULL OR email ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
    phone       VARCHAR(20)
        CHECK (phone IS NULL OR phone ~ '^\+?[0-9]{6,15}$')
);
CREATE UNIQUE INDEX uq_supplier_email ON supplier (lower(email));

-- =========================
-- CATEGORY & PRODUCT
-- =========================

-- [v2] Категорија не смее да биде сопствен родител; име уникатно во рамки на родител.
CREATE TABLE category
(
    category_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100) NOT NULL CHECK (name <> ''),
    description        TEXT,
    parent_category_id INT,
    CONSTRAINT fk_category_self
        FOREIGN KEY (parent_category_id) REFERENCES category (category_id)
            ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT chk_category_not_self CHECK (parent_category_id IS NULL OR parent_category_id <> category_id),
    CONSTRAINT uq_category_name UNIQUE NULLS NOT DISTINCT (parent_category_id, name)
);

CREATE TABLE product
(
    product_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(150)   NOT NULL CHECK (name <> ''),
    description  TEXT,
    price        NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    is_active    BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,   -- [v2]
    category_id  INT            NOT NULL,
    manufacturer VARCHAR(100),
    CONSTRAINT fk_product_category
        FOREIGN KEY (category_id) REFERENCES category (category_id)
            ON DELETE RESTRICT ON UPDATE CASCADE
);

-- [v2] Еден атрибут (пр. 'RAM') само еднаш по производ.
CREATE TABLE product_attribute
(
    product_attribute_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(100) NOT NULL,
    value                VARCHAR(255) NOT NULL,
    product_id           INT NOT NULL,
    CONSTRAINT fk_product_attribute_product
        FOREIGN KEY (product_id) REFERENCES product (product_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_product_attribute UNIQUE (product_id, name)
);

-- [v2] Набавна цена — корисна за погледи (маржа по добавувач).
CREATE TABLE product_supplier
(
    product_supplier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          INT NOT NULL,
    supplier_id         INT NOT NULL,
    purchase_price      NUMERIC(10, 2) CHECK (purchase_price IS NULL OR purchase_price > 0),
    CONSTRAINT fk_product_supplier_product
        FOREIGN KEY (product_id) REFERENCES product (product_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_product_supplier_supplier
        FOREIGN KEY (supplier_id) REFERENCES supplier (supplier_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_product_supplier UNIQUE (product_id, supplier_id)
);

-- =========================
-- PRICING
-- =========================

-- [v2] Цена > 0 и најмногу една промена по ден за ист производ.
CREATE TABLE price_history
(
    price_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date             DATE           NOT NULL DEFAULT CURRENT_DATE,
    price            NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    product_id       INT            NOT NULL,
    CONSTRAINT fk_price_history_product
        FOREIGN KEY (product_id) REFERENCES product (product_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_price_history UNIQUE (product_id, date)
);

-- [v2] Попуст од 0% нема смисла -> (0, 100]; проверката за датуми е
--      табелна (Postgres препорачува column CHECK да гледа само своја колона).
CREATE TABLE promotion
(
    promotion_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    percent      NUMERIC(5, 2) NOT NULL CHECK (percent > 0 AND percent <= 100),
    start_date   DATE          NOT NULL,
    end_date     DATE          NOT NULL,
    product_id   INT           NOT NULL,
    CONSTRAINT fk_promotion_product
        FOREIGN KEY (product_id) REFERENCES product (product_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT chk_promotion_dates CHECK (start_date <= end_date)
);

-- =========================
-- ORDER SYSTEM
-- =========================

-- [v2] Додаден tracking_number (беше во ЕР) и delivered_date; статусот е задолжителен.
CREATE TABLE shipping
(
    shipping_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date            DATE         NOT NULL DEFAULT CURRENT_DATE,
    delivered_date  DATE,
    status          VARCHAR(50)  NOT NULL DEFAULT 'preparing'
        CHECK (status IN ('preparing', 'in_transit', 'delivered', 'returned')),
    carrier         VARCHAR(100),
    tracking_number VARCHAR(100) UNIQUE,
    CONSTRAINT chk_shipping_dates CHECK (delivered_date IS NULL OR delivered_date >= date),
    CONSTRAINT chk_shipping_delivered CHECK (status <> 'delivered' OR delivered_date IS NOT NULL)
);

-- [v2] "order" -> orders: ORDER е резервиран збор, инаку секое прашање бара наводници.
-- [v2] date_payed -> date_paid (правопис).
-- [v2] address_id: на која адреса се испорачува. Композитниот FK гарантира
--      дека адресата му припаѓа токму на тој купувач.
-- [v2] Бришење купувач НЕ ги брише нарачките (RESTRICT) — историјата на
--      продажба мора да остане; купувачот се деактивира со is_active.
-- [v2] Платена/испратена/доставена нарачка мора да има date_paid.
-- [v2] Една пратка припаѓа на најмногу една нарачка (UNIQUE shipping_id).
CREATE TABLE orders
(
    order_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_ordered   TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status         VARCHAR(50)    NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
    date_paid      TIMESTAMP,
    amount         NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    method_payment VARCHAR(50)    NOT NULL
        CHECK (method_payment IN ('card', 'cash_on_delivery', 'bank_transfer', 'installments')),
    customer_id    INT            NOT NULL,
    address_id     INT            NOT NULL,
    shipping_id    BIGINT UNIQUE,
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customer (customer_id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_orders_customer_address
        FOREIGN KEY (customer_id, address_id) REFERENCES address_customer (customer_id, address_id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_orders_shipping
        FOREIGN KEY (shipping_id) REFERENCES shipping (shipping_id)
            ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT chk_orders_payment_date
        CHECK (date_paid IS NULL OR date_paid >= date_ordered),
    CONSTRAINT chk_orders_paid_has_date
        CHECK (status NOT IN ('paid', 'shipped', 'delivered') OR date_paid IS NOT NULL)
);

-- [v2] PK installment_id (во ЕР стои loan_id — усогласете).
--      Додадени: реден број на рата, рок, дали е платена.
CREATE TABLE installments
(
    installment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installment_no SMALLINT       NOT NULL CHECK (installment_no BETWEEN 1 AND 60),
    amount         NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    due_date       DATE           NOT NULL,
    paid_at        TIMESTAMP,
    bank           VARCHAR(100),
    order_id       BIGINT         NOT NULL,
    CONSTRAINT fk_installments_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_installment UNIQUE (order_id, installment_no)
);

-- [v2] unit_price: цената во моментот на купување. Без неа, промена на
--      product.price ги менува и старите нарачки (грешни приходи во погледи).
-- [v2] Колоната date од ЕР е тргната — датумот е во orders.
CREATE TABLE order_item
(
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status        VARCHAR(50)    NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'processed', 'shipped', 'delivered', 'cancelled')),
    order_id      BIGINT         NOT NULL,
    product_id    INT            NOT NULL,
    quantity      INT            NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    CONSTRAINT fk_order_item_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_order_item_product
        FOREIGN KEY (product_id) REFERENCES product (product_id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT uq_order_item UNIQUE (order_id, product_id)
);

-- =========================
-- INVENTORY
-- =========================

-- [v2] Тргнат self-reference warehousewarehouse_id од ЕР (нема значење).
CREATE TABLE warehouse
(
    warehouse_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL UNIQUE,
    city         VARCHAR(100) NOT NULL,
    number       VARCHAR(20),
    street       VARCHAR(100),
    country      VARCHAR(100) NOT NULL DEFAULT 'North Macedonia'
);

-- [v2] Најважна поправка во магацинот: табелата немаше колона за самиот
--      сериски број! Додадени: serial_code (уникатен), статус, датум на
--      прием и order_item_id — кој продаден уред е во која ставка
--      (гаранција, враќања). Продаден уред мора да има order_item_id.
CREATE TABLE serial_number
(
    serial_number_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_code      VARCHAR(64) NOT NULL UNIQUE,
    status           VARCHAR(20) NOT NULL DEFAULT 'in_stock'
        CHECK (status IN ('in_stock', 'reserved', 'sold', 'returned', 'defective')),
    received_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    product_id       INT         NOT NULL,
    warehouse_id     INT         NOT NULL,
    order_item_id    BIGINT,
    CONSTRAINT fk_serial_product
        FOREIGN KEY (product_id) REFERENCES product (product_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_serial_warehouse
        FOREIGN KEY (warehouse_id) REFERENCES warehouse (warehouse_id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_serial_order_item
        FOREIGN KEY (order_item_id) REFERENCES order_item (order_item_id)
            ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT chk_serial_sold CHECK (status <> 'sold' OR order_item_id IS NOT NULL)
);

-- =========================
-- REVIEWS & RETURNS
-- =========================

CREATE TABLE review
(
    review_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating        SMALLINT  NOT NULL CHECK (rating BETWEEN 1 AND 5),
    date          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    comment       TEXT,
    order_item_id BIGINT    NOT NULL UNIQUE,
    CONSTRAINT fk_review_order_item
        FOREIGN KEY (order_item_id) REFERENCES order_item (order_item_id)
            ON DELETE CASCADE ON UPDATE CASCADE
);

-- [v2] is_approved е тргнат — дуплира status = 'approved' и може да си
--      противречат. Додадени quantity и resolved_at. Одлучено враќање мора
--      да има вработен.
CREATE TABLE returns
(
    return_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date          DATE        NOT NULL DEFAULT CURRENT_DATE,
    reason        VARCHAR(255),
    quantity      INT         NOT NULL DEFAULT 1 CHECK (quantity > 0),
    status        VARCHAR(50) NOT NULL DEFAULT 'requested'
        CHECK (status IN ('requested', 'approved', 'rejected', 'completed')),
    resolved_at   TIMESTAMP,
    order_item_id BIGINT      NOT NULL,
    employee_id   INT,
    CONSTRAINT fk_returns_order_item
        FOREIGN KEY (order_item_id) REFERENCES order_item (order_item_id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_returns_employee
        FOREIGN KEY (employee_id) REFERENCES employee (employee_id)
            ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT chk_returns_decided
        CHECK (status = 'requested' OR employee_id IS NOT NULL)
);

-- =========================
-- SUPPORT
