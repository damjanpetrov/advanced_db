-- =====================================================================
--  Миграција 001 — телефон на купувач: и меѓународни броеви
--  Причина: купувачите може да се од странство (одлука на тимот, Фаза 2Б).
--  Нов формат: македонски локален (0 + 8 цифри) или меѓународен E.164 (+ код на земја, 8–15 цифри).
--  Вработените остануваат само со македонски формат.
--  Истата промена е внесена и во 00_ddl/ddl_v2.sql.
-- =====================================================================
ALTER TABLE customer DROP CONSTRAINT IF EXISTS customer_phone_check;
ALTER TABLE customer ADD CONSTRAINT customer_phone_check
    CHECK (phone IS NULL OR phone ~ '^(\+[1-9][0-9]{7,14}|0[0-9]{8})$');
